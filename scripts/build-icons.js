'use strict';
// Generates src/renderer/icons.js from the Lucide icon set (https://lucide.dev, ISC licence).
// Only the icons the app uses are bundled.  Run: npm run icons:ui
const fs = require('fs');
const path = require('path');

const USED = {
  upload: 'upload', play: 'play', pause: 'pause', back: 'rewind', fwd: 'fast-forward',
  noise: 'wind', hum: 'zap', rumble: 'vibrate', echo: 'house', declip: 'bandage',
  tone: 'sliders-vertical', deess: 'mic-vocal', level: 'scale', scissors: 'scissors', gauge: 'gauge',
  good: 'circle-check', warn: 'triangle-alert', bad: 'octagon-alert', info: 'info', x: 'x', check: 'check',
  download: 'download', folder: 'folder-open', refresh: 'refresh-cw', reset: 'rotate-ccw',
  'file-audio': 'file-audio', 'file-video': 'file-video', clock: 'clock', sparkles: 'sparkles',
  shield: 'shield-check', lock: 'lock', loader: 'loader-circle', film: 'film', wave: 'audio-lines',
  headphones: 'headphones', sliders: 'sliders-horizontal',
};

const dir = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');
const out = {};
for (const [key, name] of Object.entries(USED)) {
  const svg = fs.readFileSync(path.join(dir, name + '.svg'), 'utf8');
  out[key] = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
}

const js = `'use strict';
/* Generated by scripts/build-icons.js from Lucide (https://lucide.dev, ISC licence). Do not edit. */
(function () {
  const P = ${JSON.stringify(out, null, 2)};
  function svg(name, cls) {
    const body = P[name];
    if (!body) return '';
    return '<svg class="ico ' + (cls || '') + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + body + '</svg>';
  }
  function hydrate(root) {
    (root || document).querySelectorAll('[data-icon]').forEach((el) => {
      if (el.dataset.iconDone === el.dataset.icon) return;
      el.innerHTML = svg(el.dataset.icon);
      el.dataset.iconDone = el.dataset.icon;
    });
  }
  window.Icons = { svg, hydrate };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'icons.js'), js);
console.log(`icons.js written (${Object.keys(out).length} icons)`);
